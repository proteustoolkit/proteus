@pytest.mark.parametrize("name,cell,p,make", FEMTOOLS, ids=FEMTOOLS_IDS)
def test_femtools_trace_values_and_gradients_on_every_face(name, cell, p, make):
    lfs = make()
    space = _oracle_space(cell, p)
    perm = _match(lfs, space)
    ref = _ReferenceOnlySpace(lfs)
    elem = lfs.referenceElement
    face_xi, face_x = T(space, "face_xi"), T(space, "face_x")
    nf, nq = face_xi.shape[:2]
    assert elem.nElementBoundaries == nf
    # the face maps themselves (the oracle's own parametrisation is the documented FemTools one)
    for f in range(nf):
        for k in range(nq):
            assert np.abs(elem.boundaryMapList[f](face_xi[f, k]) - face_x[f, k]).max() < 1.0e-14
    # the routines take one set of face points and evaluate it on every face; the oracle uses the same
    # points on every face, so the arrays are directly comparable
    for f in range(nf):
        assert np.abs(face_xi[f] - face_xi[0]).max() == 0.0
    xi = face_xi[0]
    psi = ref.getBasisValuesTraceRef(xi)
    grad = ref.getBasisGradientValuesTraceRef(xi)
    err_v = np.abs(psi[:, :, perm] - T(space, "face_val")).max(axis=(1, 2))
    err_g = np.abs(grad[:, :, perm, :] - T(space, "face_grad")).max(axis=(1, 2, 3))
    for f in range(nf):
        assert err_v[f] < ATOL, "trace values wrong on face %d by %g" % (f, err_v[f])
        assert err_g[f] < ATOL, "trace gradients wrong on face %d by %g" % (f, err_g[f])


@pytest.mark.parametrize("name,cell,p,make", [f for f in FEMTOOLS if f[2] == 2], ids=[f[0] for f in FEMTOOLS if f[2] == 2])
def test_femtools_trace_gradients_would_catch_a_wrong_face(name, cell, p, make):
    """Negative control for the test above: gradients taken on another face differ for p = 2."""
    if cell == "interval":
        pytest.skip("a 1D face is a point, its parameter is ignored")
    lfs = make()
    space = _oracle_space(cell, p)
    perm = _match(lfs, space)
    ref = _ReferenceOnlySpace(lfs)
    grad = ref.getBasisGradientValuesTraceRef(T(space, "face_xi")[0])[:, :, perm, :]
    face_grad = T(space, "face_grad")
    assert np.abs(grad[-1] - face_grad[0]).max() > 1.0e-3


@pytest.mark.parametrize("cell", ["triangle", "tetrahedron", "quadrilateral", "hexahedron"])
def test_femtools_reference_faces_are_consistent(cell):
    """Unit normals are outward and orthogonal to the face; Jacobian columns span the face."""
    make = {"triangle": lambda: FemTools.LinearOnSimplexWithNodalBasis(2),
            "tetrahedron": lambda: FemTools.LinearOnSimplexWithNodalBasis(3),
            "quadrilateral": lambda: FemTools.LinearOnCubeWithNodalBasis(2),
            "hexahedron": lambda: FemTools.LinearOnCubeWithNodalBasis(3)}[cell]
    elem = make().referenceElement
    centroid = np.mean(elem.nodeList, axis=0)
    space = _oracle_space(cell, 1)
    face_xi = T(space, "face_xi")
    for f in range(elem.nElementBoundaries):
        n = elem.boundaryUnitNormalList[f]
        J = elem.boundaryJacobianList[f]
        assert abs(np.linalg.norm(n) - 1.0) < 1.0e-14
        assert np.abs(J.T @ n).max() < 1.0e-14
        pts = np.array([elem.boundaryMapList[f](xi) for xi in face_xi[f]])
        assert (np.dot(pts - centroid, n) > 0.0).all(), "normal of face %d points inward" % f
        # the face points differ by J (xi - xi0)
        assert np.abs((pts[1:] - pts[0]) - (face_xi[f][1:] - face_xi[f][0]) @ J.T).max() < 1.0e-14
