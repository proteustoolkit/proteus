"""
Pinned reference tables for local finite element spaces, and FemTools checked against them.

``test/fem_oracle/reference_tables.npz`` holds values, gradients and Hessians of Lagrange (equispaced and
GLL / warp-and-blend nodes), Bernstein and Q_k bases at fixed sample points of the reference cell and on each
face, generated by ``test/fem_oracle/generate_reference_tables.py`` from the sympy derivations in
``cekees/AnalyticalADR`` (see the generator for provenance and the table layout). These tests read the
pinned file only; sympy is needed to regenerate it, not to run them.

Part 1 asserts the properties the tables must have (so a bad regeneration is caught): partition of unity,
the Kronecker property, Bernstein non-negativity and linear precision, exact reproduction of polynomials of
degree <= p with their gradients and Hessians, the GLL node set (edges, symmetry).

Part 2 compares today's ``FemTools`` reference elements (P1/P2 on simplices, Q1/Q2 on cubes) with the
tables: values, gradients, Hessians, and the trace values and gradients on every face, through the same
``ParametricFiniteElementSpace`` routines the kernels use. The comparison is independent of the local dof
ordering: FemTools' functions are matched to the oracle's by their nodes.
"""
import itertools
import os

import numpy as np
import pytest

from proteus import FemTools

TABLES = os.path.join(os.path.dirname(os.path.abspath(__file__)), "fem_oracle", "reference_tables.npz")
_data = np.load(TABLES)
ALL = {k: _data[k] for k in _data.files}

SPACES = sorted({tuple(k.split("/")[:3]) for k in ALL if not k.startswith("meta")},
                key=lambda s: (s[1], s[2], s[0]))
SPACE_IDS = ["-".join(s) for s in SPACES]
SIMPLEX = ("interval", "triangle", "tetrahedron")
DIM = {"interval": 1, "triangle": 2, "tetrahedron": 3, "quadrilateral": 2, "hexahedron": 3}
ATOL = 1.0e-12


def T(space, item):
    return ALL["%s/%s/%s/%s" % (space + (item,))]


def degree(space):
    return int(space[2][1:])


def test_pinned_file_covers_the_requested_spaces():
    have = set(SPACES)
    for cell in SIMPLEX:
        for p in range(1, 5):
            for family in ("lagrange_equi", "lagrange_gll", "bernstein"):
                assert (family, cell, "p%d" % p) in have
    for cell in ("quadrilateral", "hexahedron"):
        for p in (1, 2):
            assert ("lagrange_equi", cell, "p%d" % p) in have


