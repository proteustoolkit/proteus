# Part 1: properties of the tables
# ----------------------------------------------------------------------------------------------
def _cell_and_face(space):
    """(x, val, grad, hess) at the interior points, and the same stacked over the face points."""
    x, v, g, h = (T(space, i) for i in ("x", "val", "grad", "hess"))
    d = x.shape[1]
    fx = T(space, "face_x").reshape(-1, d)
    n = v.shape[1]
    fv = T(space, "face_val").reshape(-1, n)
    fg = T(space, "face_grad").reshape(-1, n, d)
    fh = T(space, "face_hess").reshape(-1, n, d, d)
    return (x, v, g, h), (fx, fv, fg, fh)


@pytest.mark.parametrize("space", SPACES, ids=SPACE_IDS)
def test_shapes(space):
    cell = space[1]
    d = DIM[cell]
    n = T(space, "lattice").shape[0]
    assert T(space, "lattice").shape == (n, d)
    m = T(space, "x").shape[0]
    assert m >= n  # enough points to fit the polynomial reproduction test
    assert T(space, "val").shape == (m, n)
    assert T(space, "grad").shape == (m, n, d)
    assert T(space, "hess").shape == (m, n, d, d)
    nf = T(space, "face_x").shape[0]
    assert nf == (d + 1 if cell in SIMPLEX else 2 * d)
    nq = T(space, "face_x").shape[1]
    assert T(space, "face_val").shape == (nf, nq, n)
    assert T(space, "face_grad").shape == (nf, nq, n, d)
    assert T(space, "face_hess").shape == (nf, nq, n, d, d)
    assert T(space, "face_xi").shape[:2] == (nf, nq)


@pytest.mark.parametrize("space", SPACES, ids=SPACE_IDS)
def test_partition_of_unity(space):
    for (x, v, g, h) in _cell_and_face(space):
        assert np.abs(v.sum(axis=1) - 1.0).max() < ATOL
        assert np.abs(g.sum(axis=1)).max() < ATOL
        assert np.abs(h.sum(axis=1)).max() < ATOL


@pytest.mark.parametrize("space", [s for s in SPACES if s[0] != "bernstein"],
                         ids=[i for s, i in zip(SPACES, SPACE_IDS) if s[0] != "bernstein"])
def test_kronecker_property(space):
    nv = T(space, "node_val")
    assert np.abs(nv - np.eye(nv.shape[0])).max() < 1.0e-13


@pytest.mark.parametrize("space", [s for s in SPACES if s[0] == "bernstein"],
                         ids=[i for s, i in zip(SPACES, SPACE_IDS) if s[0] == "bernstein"])
def test_bernstein_nonnegative_and_linear_precision(space):
    for (x, v, g, h) in _cell_and_face(space):
        assert v.min() > -1.0e-14
        lat = T(space, "lattice")
        # Greville abscissae: sum_j lattice_j phi_j(x) = x, and the gradients reproduce the identity
        assert np.abs(v @ lat - x).max() < ATOL
        assert np.abs(np.einsum("jd,mje->mde", lat, g) - np.eye(x.shape[1])).max() < ATOL


def _exponents(cell, p):
    d = DIM[cell]
    if cell in SIMPLEX:
        return [a for a in itertools.product(range(p + 1), repeat=d) if sum(a) <= p]
    return list(itertools.product(range(p + 1), repeat=d))


def _poly(exps, coef, x):
    """q, grad q, Hessian q of sum_a coef_a x^a at points x (m, d)."""
    m, d = x.shape
    q = np.zeros(m)
    gq = np.zeros((m, d))
    hq = np.zeros((m, d, d))
    for c, a in zip(coef, exps):
        a = np.array(a)

        def mono(da):
            """x^(a - da) times falling factorial, zero when a - da < 0."""
            e = a - da
            if (e < 0).any():
                return np.zeros(m)
            f = 1.0
            for i in range(d):
                for s in range(da[i]):
                    f *= a[i] - s
            return f * np.prod(x ** e, axis=1)
        q += c * mono(np.zeros(d, int))
        for i in range(d):
            di = np.zeros(d, int)
            di[i] = 1
            gq[:, i] += c * mono(di)
            for j in range(d):
                dij = di.copy()
                dij[j] += 1
                hq[:, i, j] += c * mono(dij)
    return q, gq, hq


@pytest.mark.parametrize("space", SPACES, ids=SPACE_IDS)
def test_polynomials_up_to_p_are_reproduced_with_exact_gradients_and_hessians(space):
    cell, p = space[1], degree(space)
    exps = _exponents(cell, p)
    coef = np.random.RandomState(7).uniform(-1.0, 1.0, size=len(exps))
    (x, v, g, h), (fx, fv, fg, fh) = _cell_and_face(space)
    q, gq, hq = _poly(exps, coef, x)
    if space[0] == "bernstein":
        # coefficients by least squares (conditioning costs a few digits, hence the looser tolerance)
        c, *_ = np.linalg.lstsq(v, q, rcond=None)
        tol = 1.0e-10
    else:
        c = _poly(exps, coef, T(space, "lattice"))[0]  # nodal interpolant: coefficients are node values
        tol = 1.0e-11
    assert np.abs(v @ c - q).max() < tol  # q is in the span of the basis
    assert np.abs(np.einsum("j,mjd->md", c, g) - gq).max() < tol
    assert np.abs(np.einsum("j,mjde->mde", c, h) - hq).max() < tol
    fq, fgq, fhq = _poly(exps, coef, fx)
    assert np.abs(fv @ c - fq).max() < tol
    assert np.abs(np.einsum("j,mjd->md", c, fg) - fgq).max() < tol
    assert np.abs(np.einsum("j,mjde->mde", c, fh) - fhq).max() < tol


@pytest.mark.parametrize("space", SPACES, ids=SPACE_IDS)
def test_polynomials_above_p_are_not_in_the_span(space):
    """Negative control: the reproduction test above has power."""
    cell, p = space[1], degree(space)
    d = DIM[cell]
    x, v = T(space, "x"), T(space, "val")
    e = np.zeros(d, int)
    e[0] = p + 1
    q = np.prod(x ** e, axis=1)
    c, *_ = np.linalg.lstsq(v, q, rcond=None)
    assert np.abs(v @ c - q).max() > 1.0e-6


def _barycentric(pts):
    return np.hstack([1.0 - pts.sum(axis=1, keepdims=True), pts])


def _same_set(a, b, tol=1.0e-12):
    return all(np.abs(b - r).max(axis=1).min() < tol for r in a) and \
        all(np.abs(a - r).max(axis=1).min() < tol for r in b)


@pytest.mark.parametrize("cell", ["triangle", "tetrahedron"])
@pytest.mark.parametrize("p", [1, 2, 3, 4])
def test_gll_nodes_are_symmetric_and_equal_equispaced_through_p2(cell, p):
    lat = T(("lagrange_gll", cell, "p%d" % p), "lattice")
    eq = T(("lagrange_equi", cell, "p%d" % p), "lattice")
    if p <= 2:
        assert np.abs(lat - eq).max() < 1.0e-14
    else:
        assert np.abs(lat - eq).max() > 1.0e-3  # actually moved
    bary = _barycentric(lat)
    for perm in itertools.permutations(range(bary.shape[1])):
        assert _same_set(bary[:, list(perm)][:, 1:], lat), \
            "GLL/warp-blend nodes of %s p=%d are not invariant under barycentric permutation %s" % (cell, p, perm)
    assert (bary > -1.0e-12).all()


@pytest.mark.parametrize("p", [3, 4])
def test_gll_triangle_edge_nodes_are_the_1d_gll_points(p):
    lat = T(("lagrange_gll", "triangle", "p%d" % p), "lattice")
    line = T(("lagrange_gll", "interval", "p%d" % p), "lattice")[:, 0]
    bary = _barycentric(lat)
    for k in range(3):
        on_edge = np.abs(bary[:, k]) < 1.0e-12
        assert on_edge.sum() == p + 1
        # parameter along the edge: the largest barycentric coordinate other than k, ordered
        others = [i for i in range(3) if i != k]
        s = np.sort(bary[on_edge][:, others[0]])
        assert np.abs(s - np.sort(line)).max() < 1.0e-12


