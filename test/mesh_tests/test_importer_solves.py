"""A P1 Poisson solve on each in-tree importer's mesh, serial against two ranks (C7.1 round 3).

importer_solve_mpi.py solves -Laplace(u) = -2 nd with u = |x|^2 on the nodes the importer tagged
(a positive tag); the tests compare the nodal solution from one rank and from two (a direct solve,
so they differ by round-off), and pin the nodal error of the serial run, which an untagged or
mis-tagged boundary, a shifted node or a lost element would change. The meshes are stored or
generated by proteus itself, so the error is the same on every machine.

The driver starts its own ranks, so these tests skip under a multi-rank launch.
"""
import os
import shutil
import subprocess
import sys

import numpy as np
import pytest

HERE = os.path.dirname(os.path.abspath(__file__))


def _launcher_env(extra):
    env = dict((k, v) for k, v in os.environ.items() if not k.startswith(("PMI_", "PMIX_", "HYDRA_", "OMPI_COMM_WORLD")))
    env["PYTHONPATH"] = os.pathsep.join([p for p in sys.path if p] + [env.get("PYTHONPATH", "")]).strip(os.pathsep)
    env.setdefault("OMPI_MCA_rmaps_base_oversubscribe", "1")
    env.setdefault("PRTE_MCA_rmaps_default_mapping_policy", ":oversubscribe")
    env.setdefault("FI_PROVIDER", "tcp")
    env["OMP_NUM_THREADS"] = "1"
    env["PETSC_OPTIONS"] = "-mat_partitioning_type current"
    env.update(extra)
    return env


def _mpiexec():
    for name in ("PMI_SIZE", "OMPI_COMM_WORLD_SIZE", "PMIX_SIZE"):
        if int(os.environ.get(name, "1")) > 1:
            pytest.skip("launches its own mpiexec; run this file serially")
    beside = os.path.join(os.path.dirname(sys.executable), "mpiexec")
    found = beside if os.path.exists(beside) else shutil.which("mpiexec")
    if found is None:
        pytest.skip("no MPI launcher available")
    return found


def solve(tmp_path, kind, ranks, **env):
    """The driver's result on ``ranks`` ranks: (npz arrays, its RESULT line)."""
    cwd = tmp_path / ("%s_%d_%s" % (kind, ranks, "_".join("%s%s" % kv for kv in sorted(env.items()))))
    cwd.mkdir()
    result = subprocess.run([_mpiexec(), "-n", str(ranks), sys.executable,
                             os.path.join(HERE, "importer_solve_mpi.py"), kind, "out"],
                            capture_output=True, text=True, env=_launcher_env(env), cwd=str(cwd), timeout=600)
    assert result.returncode == 0, result.stdout[-3000:] + result.stderr[-3000:]
    line = [l for l in result.stdout.splitlines() if l.startswith("RESULT")]
    assert line, result.stdout[-3000:] + result.stderr[-3000:]
    return dict(np.load(str(cwd / "out.npz"))), line[0]


def assert_same_solution(serial, parallel):
    np.testing.assert_array_equal(serial["x"], parallel["x"])
    assert np.abs(serial["u"] - parallel["u"]).max() <= 1.0e-12 * np.abs(serial["u"]).max()


def nodal_error(result):
    return np.abs(result["u"] - (result["x"] ** 2).sum(axis=1)).max()


@pytest.mark.parametrize("kind, nodes, error", [
    ("gmsh2d", 98, 3.984621e-03),
    ("gmsh3d", 341, 2.286453e-02),
])
def test_a_gmsh_mesh_solves_the_same_on_two_ranks(tmp_path, kind, nodes, error):
    serial, _ = solve(tmp_path, kind, 1)
    parallel, line = solve(tmp_path, kind, 2)
    assert len(serial["u"]) == nodes
    assert all(o > 0 for o in parallel["owned"]), line
    assert_same_solution(serial, parallel)
    assert nodal_error(serial) == pytest.approx(error, rel=1.0e-6)
